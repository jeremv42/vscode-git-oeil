// Parsing of git output. No vscode dependency: tested with node:test.

export const UNCOMMITTED_SHA = '0'.repeat(40);

export interface CommitInfo {
  sha: string;
  author: string;
  authorMail: string; // without the angle brackets
  authorTime: number; // epoch seconds
  summary: string;
}

export interface Blame {
  /** Commit sha for each line (index 0 = line 1). */
  lines: string[];
  commits: Map<string, CommitInfo>;
}

const BLAME_HEADER = /^([0-9a-f]{40}) \d+ (\d+)(?: \d+)?$/;

/** Output of `git blame --porcelain`. */
export function parseBlamePorcelain(out: string): Blame {
  const lines: string[] = [];
  const commits = new Map<string, CommitInfo>();
  let current: CommitInfo | undefined;
  let finalLine = 0;

  for (const raw of out.split('\n')) {
    if (raw.startsWith('\t')) {
      if (current) lines[finalLine - 1] = current.sha;
      continue;
    }
    const header = BLAME_HEADER.exec(raw);
    if (header) {
      const sha = header[1];
      finalLine = Number(header[2]);
      current = commits.get(sha);
      if (!current) {
        current = { sha, author: '', authorMail: '', authorTime: 0, summary: '' };
        commits.set(sha, current);
      }
      continue;
    }
    if (!current) continue;
    const space = raw.indexOf(' ');
    const key = space < 0 ? raw : raw.slice(0, space);
    const value = space < 0 ? '' : raw.slice(space + 1);
    switch (key) {
      case 'author':
        current.author = value;
        break;
      case 'author-mail':
        current.authorMail = value.replace(/^<|>$/g, '');
        break;
      case 'author-time':
        current.authorTime = Number(value);
        break;
      case 'summary':
        current.summary = value;
        break;
    }
  }
  return { lines, commits };
}

export interface Branch {
  name: string;
  current: boolean;
  upstream: string;
  /** "↑1 ↓2", "upstream gone" or ''. */
  track: string;
  time: number; // last commit date, epoch seconds
  subject: string;
}

export const BRANCH_FORMAT =
  '%(HEAD)%00%(refname:short)%00%(upstream:short)%00%(upstream:track,nobracket)%00%(committerdate:unix)%00%(subject)';

/** Output of `git for-each-ref --format=BRANCH_FORMAT refs/heads`. */
export function parseBranches(out: string): Branch[] {
  return out
    .split('\n')
    .filter((l) => l.length > 0)
    .map((l) => {
      const [head, name, upstream, track, time, subject] = l.split('\0');
      return {
        name,
        current: head === '*',
        upstream: upstream ?? '',
        track: formatTrack(track ?? ''),
        time: Number(time) || 0,
        subject: subject ?? '',
      };
    });
}

function formatTrack(track: string): string {
  if (track === 'gone') return 'upstream gone';
  const ahead = /ahead (\d+)/.exec(track);
  const behind = /behind (\d+)/.exec(track);
  return [ahead && `↑${ahead[1]}`, behind && `↓${behind[1]}`].filter(Boolean).join(' ');
}

export interface Stash {
  ref: string; // stash@{0}
  sha: string;
  time: number;
  branch: string;
  message: string;
  wip: boolean; // message generated by git ("WIP on …")
}

export const STASH_FORMAT = '%gd%x00%H%x00%ct%x00%gs';

/** Output of `git stash list --format=STASH_FORMAT`. */
export function parseStashes(out: string): Stash[] {
  return out
    .split('\n')
    .filter((l) => l.length > 0)
    .map((l) => {
      const [ref, sha, time, subject = ''] = l.split('\0');
      const m = /^(WIP on|On) ([^:]+): (.*)$/.exec(subject);
      return {
        ref,
        sha,
        time: Number(time) || 0,
        branch: m ? m[2] : '',
        message: m ? m[3] : subject,
        wip: m ? m[1] === 'WIP on' : false,
      };
    });
}

export interface RecentBranch {
  name: string;
  time: number; // last time the branch was checked out or left, epoch seconds
}

export const REFLOG_FORMAT = '%gd%x00%gs';

/**
 * Recently used branches, from `git reflog show --date=unix --format=REFLOG_FORMAT HEAD`
 * (newest entries first). Keeps only local branches that still exist, minus the current one.
 */
export function recentBranches(
  reflog: string,
  existing: ReadonlySet<string>,
  current: string | undefined,
  max: number,
): RecentBranch[] {
  const result: RecentBranch[] = [];
  const seen = new Set<string>();
  if (current) seen.add(current);

  for (const line of reflog.split('\n')) {
    if (result.length >= max) break;
    const [selector = '', subject = ''] = line.split('\0');
    const m = /^checkout: moving from (.+) to (.+)$/.exec(subject);
    if (!m) continue;
    const time = Number(/@\{(\d+)\}$/.exec(selector)?.[1]) || 0;
    // Destination then origin: both branches were in use at that moment.
    for (const name of [m[2], m[1]]) {
      if (seen.has(name) || !existing.has(name)) continue;
      seen.add(name);
      result.push({ name, time });
      if (result.length >= max) break;
    }
  }
  return result;
}
